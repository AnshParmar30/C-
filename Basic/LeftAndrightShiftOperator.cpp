#include<bits/stdc++.h>
using namespace std;
int main(){
    // Left Shift. : 
    // The formula is : a*2^n here n = 4.
    int a = 2<<4;
    cout<<"the value of a after 3 left shift is : "<<a<<"\n";

    // Right Shift. : 
    // The formula is : b/2^n here n = 2.
    int b = 16>>2;
    cout<<"The value of b after 3 right shifts is : "<<b<<"\n";
}